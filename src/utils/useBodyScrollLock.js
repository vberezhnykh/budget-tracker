import { useEffect } from 'react';

// Фиксация страницы под тем, что лежит поверх неё: под модальным листом
// (ui/Sheet) и под раскрытой шторкой истории (TransactionsDrawer).
//
// Само по себе это не получается. Затемнение поверх страницы жест не
// съедает: браузер прокручивает то, что под пальцем, - и главный экран
// уезжает под размытием, хотя трогали, казалось бы, неподвижный фон.
// Не помогает и overscrollBehavior на самом листе: он обрывает только
// передачу прокрутки от вложенного скроллера, а не касание, начатое
// прямо на подложке.
//
// Одного `overflow: hidden` на body тоже мало: в мобильном Safari он
// касание не останавливает, поэтому страница ещё и переводится в
// position: fixed со сдвигом на текущую прокрутку - так она остаётся на
// месте визуально. При закрытии прокрутка возвращается: без этого экран
// прыгал бы наверх.
//
// Счётчик нужен на случай, когда сверху лежат сразу двое (выбор периода
// поверх другого листа; форма операции, открытая из шторки): фиксировать
// надо на первом, а возвращать прокрутку - на последнем закрытом, иначе
// второй запомнил бы уже обнулённую позицию и вернул экран не туда.
let lockCount = 0;
let lockedScrollY = 0;

// active: у листа блокировка живёт ровно столько, сколько сам лист, и
// параметр не нужен; шторка же из дерева не исчезает - она свёрнута, и
// страница под ней должна прокручиваться как обычно.
export default function useBodyScrollLock(active = true) {
    useEffect(() => {
        if (!active) return undefined;

        const { body } = document;
        if (lockCount === 0) {
            lockedScrollY = window.scrollY;
            body.style.overflow = 'hidden';
            body.style.position = 'fixed';
            body.style.width = '100%';
            body.style.top = `-${lockedScrollY}px`;
        }
        lockCount += 1;

        return () => {
            lockCount -= 1;
            if (lockCount === 0) {
                body.style.overflow = '';
                body.style.position = '';
                body.style.width = '';
                body.style.top = '';
                // Чтение offsetHeight заставляет браузер пересчитать
                // раскладку прямо здесь. Без этого страница ещё «сложена»
                // (body только что был вынут из потока), её высота меньше
                // прокрутки, и scrollTo обрезается до нуля - экран прыгает
                // наверх. Заметно это в первую очередь в dev-сборке, где
                // StrictMode монтирует эффект дважды и второй заход
                // считывает уже обнулённую позицию.
                void body.offsetHeight;
                window.scrollTo(0, lockedScrollY);
            }
        };
    }, [active]);
}
