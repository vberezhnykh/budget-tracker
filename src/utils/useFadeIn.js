import { useState } from 'react';

// Класс плавного появления для блока, который занял место скелетона.
// waiting - пока true, на месте блока скелетон (или его вообще нет). Как
// только ожидание кончилось, возвращается 'fade-in' (src/index.css), и блок
// проявляется вместо резкого скачка. flat - вариант без сдвига, только
// прозрачность: см. комментарий к @keyframes fade-in-flat.
//
// Класс выдаётся лишь тем блокам, которые застали ожидание. Блок, который
// сразу открылся с готовыми данными (возврат на вкладку, кэш), ничего не
// проигрывает: экран и так появляется своей анимацией, и две подряд дали бы
// двойное мигание. Фоновое обновление (старые данные остаются на экране,
// waiting не включается) класс не трогает, так что данные не мигают.
// Запоминание «застал ожидание» делается в состоянии, а не в ref: ref
// читать при рендере нельзя.
export default function useFadeIn(waiting, { flat = false } = {}) {
  const [sawWaiting, setSawWaiting] = useState(waiting);
  if (waiting && !sawWaiting) setSawWaiting(true);
  if (waiting || !sawWaiting) return '';
  return flat ? 'fade-in fade-in--flat' : 'fade-in';
}
