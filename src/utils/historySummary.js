// Итог под фильтрами Истории: сумма по всему найденному списку. Берётся
// dailySum дней - ровно то, что сервер уже сложил для заголовков дней: доходы
// плюс, расходы минус, переводы и стартовый баланс не идут, разделённая
// операция считается один раз (по сумме частей). Так итог всегда равен сумме
// чисел, которые человек видит над днями, и расходиться с ними ему нечему.
export function historyTotal(groups) {
  return Object.values(groups || {}).reduce((sum, group) => sum + (Number(group?.dailySum) || 0), 0);
}
