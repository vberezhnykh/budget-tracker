// Карточка: блок с поверхностью, рамкой и скруглением, внутри которого лежит
// содержимое экрана. Раньше их было две породы, и обе рисовались вручную:
// стеклянная панель главного экрана (класс glass-panel, к которому каждый
// раз дописывали отступ в style) и «белая карточка» в листах - поверхность,
// тонкая рамка, скругление 16px, - которую каждый лист собирал по памяти.
// Отступы при этом гуляли от 12 до 32px без видимой причины.
//
// Тон - это роль карточки, а не цвет:
//
//   glass - основная панель экрана: сводка, аналитика, плановые платежи.
//           Реализация осталась классом .glass-panel (размытие, стекло,
//           рамка, скругление, тень) - e2e находит такие панели именно по
//           нему, а размытие и тень в инлайн-стиль не вынести без дублей.
//   plain - карточка элемента внутри листа: операция в корзине, банк,
//           плановый платёж. Белая, на тонкой рамке, без тени - она лежит
//           на подложке листа и не должна всплывать над ней.
//   muted - пустое состояние и тихий блок: «Корзина пуста». Без рамки и
//           почти без заливки, чтобы не выглядеть кликабельным.
//
// Отступ берётся из шкалы --space-*, а не пишется числом:
//
//   none - 0: внутри карточки свои секции с собственными отступами
//          (шапка и список в шторке истории).
//   sm   - 12px: плотные строки внутри листа.
//   md   - 16px: умолчание.
//   lg   - 24px: крупные панели главного экрана.
//
// Всё, что относится к раскладке (display, flex, gap, margin, ширина),
// остаётся за вызовом - через style. Он идёт последним, поэтому может и
// точечно переопределить отступ, если карточке нужен несимметричный.
// `as` задаёт тег: article, section, aside, form.

const TONES = {
    glass: {},
    plain: {
        background: 'var(--color-surface)',
        border: '1px solid var(--color-border-subtle)',
        borderRadius: 'var(--radius-lg)',
    },
    muted: {
        background: 'var(--color-surface-muted)',
        borderRadius: 'var(--radius-lg)',
    },
};

const PADDINGS = {
    none: { padding: 0 },
    sm: { padding: 'var(--space-3)' },
    md: { padding: 'var(--space-4)' },
    lg: { padding: 'var(--space-6)' },
};

export default function Card({
    as = 'div',
    tone = 'glass',
    padding = 'md',
    className,
    style,
    children,
    ...props
}) {
    // Заглавная буква нужна JSX; eslint не считает использованием в разметке
    // параметр с таким именем, поэтому переименование - отдельной строкой.
    const Tag = as;
    const toneClass = tone === 'glass' ? 'glass-panel' : null;
    const classes = [toneClass, className].filter(Boolean).join(' ') || undefined;
    return (
        <Tag
            className={classes}
            {...props}
            style={{
                ...PADDINGS[padding],
                ...TONES[tone],
                ...style,
            }}
        >
            {children}
        </Tag>
    );
}
